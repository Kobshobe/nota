#!/usr/bin/env node
// 把演示音频编码成固件里的 base64 字符串；Wokwi 网页项目不能上传二进制文件。
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const source = process.argv[2] ?? path.join(root, 'device/fixtures/meeting-01.mp3');
const target = process.argv[3] ?? path.join(root, 'device/firmware/fixture.h');

const encoded = readFileSync(source).toString('base64');
const chunks = encoded.match(/.{1,120}/g) ?? [];
const lines = chunks.map((chunk) => `  "${chunk}"`).join('\n');

const content = `// Generated by device/tools/embed-fixture.mjs from ${path.relative(root, source)}.
#pragma once
#include <stddef.h>

static const char FIXTURE_BASE64[] =
${lines};

static const size_t FIXTURE_BASE64_LENGTH = ${encoded.length};
`;

writeFileSync(target, content);
console.log(`${path.relative(root, target)}: ${encoded.length} base64 chars`);
